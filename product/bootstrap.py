#!/usr/bin/env python3
"""Idempotent one-shot initialization in the TOEFL House ERP product stack.

Compose runs this short-lived ``bootstrap`` service successfully before the
long-lived ``web`` service starts. Everything is safe to re-run: completed
steps are detected and skipped, migrations always run (including the proven
migrate replay), and no step patches upstream code or weakens a gate.

Steps, in order (mirrors the operator/hosted sequence):

1. Wait for MariaDB and both Redis containers (TCP).
2. Point the bench's Redis URLs at the compose services (set-config --global).
3. Create the site if none exists through pinned Frappe's native installer
   (`_new_site`, MariaDB backend, default site).
4. On first run, create the Administrator password ONCE and atomically stage
   it at mode 0600 on the persistent sites volume before invoking Frappe's
   native installer. Publish it to
   ./data/sites/<site>/private/first-run-credentials.txt immediately after
   site creation; a retry reuses the pending value if either step is interrupted.
5. Install missing apps in the proven order: erpnext, education, payments,
   hrms, foundation_security, toefl_house. Already-installed apps are skipped
   (parsed from `bench list-apps`). Synthetic-only flags are never set.
6. Migrate (twice, hosted-parity; the second replay verifies idempotence).
7. Initialize the native site encryption key (the same lazy native mechanism
   the app's own after_install hook uses) so every later backup carries it.
8. Build assets when the sites/assets tree is absent (first boot only; the
   build context bakes no sites tree, the bind-mounted host dir starts empty),
   then merge every app's public/ tree into sites/assets/<app>/ whenever
   anything from a build is missing (first boot, crashed mid-build volume, or
   a recreated container from an updated image). `bench build` leaves the
   built per-app bundles in the app's public/dist/ while the
   sites/assets/assets.json manifest already references them — without this
   sync the static root 404s on the hashed bundles and login silently breaks.
9. Enable the scheduler idempotently on every boot. This repairs a partial
   first boot that stopped before scheduler activation; it does not rotate
   Administrator credentials or repeat one-time secret writes.

Secrets: the MariaDB root password arrives only in the short-lived
bootstrap service via /run/bootstrap-secrets/db.env (key=value lines,
generated by the Windows Install script). The web service never mounts that
file. Site-creation secrets are sent to the pinned Bench Python process over
stdin, not command-line arguments or logs. The Administrator password is
generated with secrets.token_urlsafe, atomically staged mode 0600 on the
persistent sites volume, then published into the site's private credentials file.
"""
